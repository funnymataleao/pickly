insert into public.product_alternatives (product_id, alternative_product_id, reason, rank)
select source.id, alternative.id, 'Lower added sugar', 1
from public.products source
join public.products alternative on alternative.barcode = '5449000131805'
where source.barcode = '5449000000996'
